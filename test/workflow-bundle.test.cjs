const test = require('node:test');
const assert = require('node:assert/strict');
const { bundleWorkflowCode } = require('@temporalio/worker');

const silent = { log() {}, trace() {}, debug() {}, info() {}, warn() {}, error() {} };

// workflows.ts must stay deterministic. Bundle it the way the worker does and check what actually got in,
// so an import chain that reaches config, the environment, Redis or fetch fails here, not in production.
test('the workflow bundle contains only the pure modules it is allowed to import', async () => {
  const { code } = await bundleWorkflowCode({ workflowsPath: require.resolve('../dist/workflows'), logger: silent });
  const ours = [...new Set([...code.matchAll(/\.\/dist\/[\w.-]+/g)].map(match => match[0]))].sort();
  assert.deepEqual(ours, ['./dist/domain.js', './dist/workflows-autogenerated-entrypoint.cjs', './dist/workflows.js']);
  for (const forbidden of ['ioredis', 'ENABLE_MOCK_FAULTS', 'TEMPORAL_ADDRESS', 'REDIS_URL', 'SUPPLIER_BASE_URL', 'enableMockFaults']) {
    assert.equal(code.includes(forbidden), false, `${forbidden} must not reach the workflow bundle`);
  }
});
